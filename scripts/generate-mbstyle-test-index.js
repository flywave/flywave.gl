/*
 * Generates a static TypeScript module exporting the list of compat
 * render-tests (name + full style object) so MBStyleCompatRenderTest can run
 * inside karma (where Node's fs is unavailable).
 *
 * Usage: node scripts/generate-mbstyle-test-index.js [filter...]
 *   Filters are substrings matched against the test name; when provided, only
 *   matching tests are included (keeps the generated bundle small).
 *   Without filters the full set is generated.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(
    __dirname,
    "..",
    "@flywave/flywave-mbstyle-datasource/test/render-tests",
);
const OUT = path.resolve(
    __dirname,
    "..",
    "@flywave/flywave-mbstyle-datasource/test/render-tests-index.ts",
);

const filters = process.argv.slice(2);

const INCOMPATIBLE_TYPES = new Set([
    "terrain",
    "globe",
    "video",
    "custom-layer",
    "raster-particle",
    "raster-array",
    "skybox",
]);

const results = [];

function scanDir(dir, prefix) {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    const stylePath = path.join(dir, "style.json");
    if (fs.existsSync(stylePath)) {
        try {
            const style = JSON.parse(fs.readFileSync(stylePath, "utf8"));
            const layers = style.layers ?? [];
            const skip = layers.some((l) => INCOMPATIBLE_TYPES.has(l.type));
            if (!skip) {
                results.push({ name: prefix, style });
            }
        } catch {}
        return;
    }
    for (const e of entries) {
        if (!e.isDirectory()) continue;
        scanDir(path.join(dir, e.name), prefix ? `${prefix}/${e.name}` : e.name);
    }
}

const topDirs = fs.readdirSync(ROOT, { withFileTypes: true });
for (const td of topDirs) {
    if (!td.isDirectory()) continue;
    scanDir(path.join(ROOT, td.name), td.name);
}

const filtered = filters.length
    ? results.filter((r) => filters.some((f) => r.name.includes(f)))
    : results;

const content = `// AUTO-GENERATED by scripts/generate-mbstyle-test-index.js — do not edit.
// Re-generate after adding/removing test/render-tests fixtures.
export interface CompatTestEntry {
    name: string;
    style: any;
}

export const ALL_TESTS: CompatTestEntry[] = ${JSON.stringify(filtered, null, 2)};
`;
fs.writeFileSync(OUT, content);
console.log(
    `[mbstyle-test-index] wrote ${filtered.length}/${results.length} tests to ${OUT}`,
);
